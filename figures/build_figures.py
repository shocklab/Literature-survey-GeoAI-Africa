def wrap(csv, indent="    ", width=88):
    """Break a comma-separated list over several lines using %-continuations,
    so no line runs to 900 characters and a diff stays readable."""
    # split on top-level commas only: a label such as {CNN, detection} holds one
    # of its own, and breaking the line there let the %-continuation eat the space
    parts, depth, cur = [], 0, ""
    for ch in csv:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    parts.append(cur)
    out, line = [], ""
    for part in parts:
        cand = (line + "," + part) if line else part
        if len(cand) > width and line:
            out.append(line + ",%")
            line = part
        else:
            line = cand
    out.append(line)
    return ("\n" + indent).join(out)


def axislabels(items):
    """items: list of (display, value) low->high. Returns (symbolic, ticklabels, coords)."""
    keys = [symkey(d) for d, _ in items]
    disp = [esc(SHORT.get(d, d)).replace("<", "$<$").replace(">", "$>$")
            for d, _ in items]
    return (",".join(keys),
            ",".join("{%s}" % d for d in disp),
            " ".join("(%d,%s)" % (v, k) for (_, v), k in zip(items, keys)))


