#!/usr/bin/env python
# =====================================================================
#  figures/fig-choropleth_tikz.py
#  Generates figures/fig-choropleth.tex -- the Africa studies-per-country
#  classed choropleth (B1), drawn natively in TikZ so the manuscript has
#  no raster figures left.
#
#  Mirrors the LOCKED B1 spec in Excel_analysis/20-06/build_figures.py:
#    * uneven right-open bins  [1,3,6,10,19,25) -> 1-2 / 3-5 / 6-9 / 10-18 / 19-24
#    * ColorBrewer Oranges starting ONE STEP DARKER so the grey zero class
#      clears the palest orange (dE 17.1, not 10.5)
#    * zero = flat neutral grey #e8e8e8, drawn as a separate layer, no hatch
#    * white country boundaries, 0.4pt
#    * y clipped at -36 to drop South Africa's sub-Antarctic Prince Edward Is.
#    * legend lower-left in the Atlantic, order 0 / 1-2 / ... / 19-24
#
#  Reads the AUTHORITATIVE workbook in Excel_analysis/20-06/, NOT the stale
#  copy in claude/ that spatio-temporal_tikz.py uses.
#
#  Regenerate with:  python figures/fig-choropleth_tikz.py
#  Edit THIS SCRIPT, never the emitted coordinates.
# =====================================================================
import os
import pandas as pd
import geopandas as gpd
from shapely.geometry import box

#HERE = os.path.dirname(os.path.abspath(__file__))
#ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "Excel_analysis", "20-06"))
GEO = os.path.join(ROOT, "Africa_Countries.geojson")
#XL = os.path.join(ROOT, "selected_articles_only.xlsx")
OUT = os.path.join(HERE, "fig-choropleth.tex")

# ---- locked B1 spec -------------------------------------------------
BIN_EDGES = [1, 3, 6, 10, 19, 25]
BIN_LABELS = ["1--2", "3--5", "6--9", "10--18", "19--24"]
BIN_COLORS = ["fdae6b", "fd8d3c", "e6550d", "a63603", "7f2704"]
ZERO_FILL = "e8e8e8"
EDGE = "white"
EDGE_W = "0.4pt"
SWATCH_EDGE = "8a8a8a"
YMIN = -36.0  # mainland clip

# ---- drawing knobs (tune here, then regenerate) ---------------------
SCALE = 0.175        # cm per degree -> picture ~15.5 cm wide
SIMPLIFY = 0.030     # degrees; ~0.005 cm at SCALE, below print resolution
MIN_AREA = 0.006     # sq deg; drop slivers that cannot render
LEG_X, LEG_Y = 0.020, 0.060   # axes-fraction anchor (matches bbox_to_anchor)
LEG_SW = 3.50        # swatch width  (degrees)
LEG_SH = 2.80        # swatch height (degrees)
LEG_DY = 4.60        # row pitch     (degrees)
LEG_GAP = 1.40       # swatch -> label gap (degrees)
# Font sizes are relative to the 12pt elsarticle base and are then shrunk by
# the \resizebox (x0.849), so set them LARGER here than you want on the page.
# Keep LEG_DY >= 1.3 x the nominal font size in degrees, i.e.
#     LEG_DY >= 1.3 * pt / (SCALE * 28.35);  \Large (17.28pt) -> 4.53
# or the legend rows collide.
FONT_LBL = r"\sffamily\Large"
FONT_TTL = r"\sffamily\Large"

# ---- data -----------------------------------------------------------
af = gpd.read_file(GEO)
af["geometry"] = af.geometry.buffer(0)  # fix 2 invalid geometries
cl = pd.read_excel(XL, sheet_name="country_long")
cnt = cl.groupby("ISO3")["study_id"].nunique().rename("studies")
af = af.merge(cnt, left_on="ISO_3DIGIT", right_index=True, how="left")
af["studies"] = af["studies"].fillna(0).astype(int)

minx, _, maxx, maxy = af.total_bounds
af["geometry"] = af.geometry.intersection(box(minx - 1, YMIN, maxx + 1, maxy + 1))
af = af[~af.geometry.is_empty].copy()

# ---- punch out enclaves --------------------------------------------
# The source geojson models enclaves as OVERLAP, not as interior rings:
# South Africa's polygon covers Lesotho entirely (no hole). Because the
# zero class is drawn first and the data class second, South Africa (24
# studies, darkest orange) would paint straight over Lesotho (0 studies,
# grey) and the enclave would vanish -- the same defect the matplotlib B1
# has. Subtract any country a polygon fully contains so the enclave
# becomes a genuine hole, rendered with the even-odd rule.
_enc = []
for i, a in af.iterrows():
    inner = af[(af.index != i) & af.geometry.within(a.geometry.buffer(1e-9))]
    if len(inner):
        af.at[i, "geometry"] = a.geometry.difference(inner.geometry.union_all())
        _enc += [(a["NAME"], n) for n in inner["NAME"]]
for outer, inner in _enc:
    print("  enclave: %s punched out of %s" % (inner, outer))

af["geometry"] = af.geometry.simplify(SIMPLIFY, preserve_topology=True)


def bin_of(n):
    if n <= 0:
        return None
    for i in range(len(BIN_EDGES) - 1):
        if BIN_EDGES[i] <= n < BIN_EDGES[i + 1]:
            return i
    return len(BIN_COLORS) - 1


def path(coords):
    pts = " -- ".join("(%.3f,%.3f)" % (x * SCALE, y * SCALE) for x, y in coords)
    return pts + " -- cycle"


dropped = 0
body = []
# zero class FIRST -- categorically outside the sequential ramp
for layer in (0, 1):
    for _, r in af.iterrows():
        if (r["studies"] == 0) != (layer == 0):
            continue
        b = bin_of(r["studies"])
        col = ZERO_FILL if b is None else BIN_COLORS[b]
        g = r.geometry
        parts = list(g.geoms) if g.geom_type == "MultiPolygon" else [g]
        for p in parts:
            if p.is_empty or p.area < MIN_AREA:
                dropped += 1
                continue
            segs = [path(list(p.exterior.coords))]
            segs += [path(list(i.coords)) for i in p.interiors]
            rule = "even odd rule," if len(p.interiors) else ""
            body.append(
                r"\fill[" + rule + "fill=mc" + col + ",draw=" + EDGE
                + ",line width=" + EDGE_W + "] " + " ".join(segs) + ";"
            )

# ---- legend ---------------------------------------------------------
x0 = (minx + LEG_X * (maxx - minx)) * SCALE
y0 = (YMIN + LEG_Y * (maxy - YMIN)) * SCALE
sw, sh = LEG_SW * SCALE, LEG_SH * SCALE
dy, gap = LEG_DY * SCALE, LEG_GAP * SCALE
entries = [(ZERO_FILL, "0")] + list(zip(BIN_COLORS, BIN_LABELS))

leg = []
for i, (col, lab) in enumerate(reversed(entries)):  # bottom-up
    y = y0 + i * dy
    leg.append(
        r"\fill[fill=mc" + col + r",draw=swatchedge,line width=0.3pt] "
        + "(%.3f,%.3f) rectangle (%.3f,%.3f);" % (x0, y, x0 + sw, y + sh)
    )
    leg.append(
        r"\node[anchor=west,font=" + FONT_LBL + ",text=black] at "
        + "(%.3f,%.3f) {%s};" % (x0 + sw + gap, y + sh / 2, lab)
    )
leg.append(
    r"\node[anchor=west,font=" + FONT_TTL + ",text=black] at "
    + "(%.3f,%.3f) {No.\\ of studies};" % (x0, y0 + len(entries) * dy)
)

colors = sorted(set(BIN_COLORS) | {ZERO_FILL})
defs = "\n".join(
    r"\definecolor{mc" + c + "}{HTML}{" + c.upper() + "}" for c in colors
)
defs += "\n" + r"\definecolor{swatchedge}{HTML}{" + SWATCH_EDGE.upper() + "}"

HEAD = r"""% =====================================================================
%  figures/fig-choropleth.tex -- studies per African country (fig:choropleth)
%  Classed choropleth, drawn natively in TikZ.
%  Requires: \usepackage{tikz} and \usepackage{xcolor} (no extra libraries).
%  AUTO-GENERATED by figures/fig-choropleth_tikz.py from
%  Excel_analysis/20-06/Africa_Countries.geojson + selected_articles_only.xlsx.
%  Edit the script and regenerate; do NOT hand-tune the coordinates.
%
%  Bins are right-open: [1,3) = "1-2" ... [19,25) = "19-24".
%  Zero countries are flat grey #E8E8E8, a hue outside the ramp and lighter
%  than every orange, so "nothing looks like nothing".
%  ISLANDS (Cabo Verde, Comoros, Mauritius, Sao Tome, Seychelles) are
%  unreadable specks at this scale -- the named zero-country table in the
%  text is MANDATORY, not decoration.
% =====================================================================
"""

MID = r"""\begin{figure}[htbp]
\centering
\resizebox{0.8\linewidth}{!}{%
\begin{tikzpicture}[font=\sffamily]
% ---- country polygons (zero class drawn first) ----
"""

TAIL = r"""\end{tikzpicture}%
}
\caption[Studies per African country]{Number of studies per African country.
Countries with no studies are shown in grey.}
\label{fig:choropleth}
\end{figure}
"""

tex = (HEAD + defs + "\n" + MID + "\n".join(body)
       + "\n% ---- legend (Atlantic dead-space, lower left) ----\n"
       + "\n".join(leg) + "\n" + TAIL)

with open(OUT, "w", encoding="utf-8") as f:
    f.write(tex)

