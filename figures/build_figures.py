def sheet(name, book=None):
    ws = (book or wb)[name]
    hdr = [str(c).strip() if c is not None else "" for c in
           next(ws.iter_rows(min_row=1, max_row=1, values_only=True))]
    return [dict(zip(hdr, r)) for r in ws.iter_rows(min_row=2, values_only=True)
            if any(v is not None for v in r)]


def split(v, seps=";"):
    if v in (None, ""):
        return []
    return [x.strip() for x in re.split("[" + seps + "]", str(v)) if x.strip()]


def normt(t):
    return re.sub(r"[^a-z0-9]", "", str(t).lower())[:60]


def blank(v):
    return v is None or str(v).strip() in ("", "-", "NA", "N/A", "None", "none")


