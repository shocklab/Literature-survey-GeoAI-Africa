# ("2000-2022"), a single year, or a list of dates ("2016;2019;2023",
# "1993, 2008, 2023"); the span is last year minus first year.
def span_years(v):
    return [int(y) for y in re.findall(r"(?<!\d)(\d{4})(?!\d)", v)]


def span_bucket(v):
    ys = span_years(v)
    if not ys:
        return None
    d = max(ys) - min(ys)
    return "Single year" if d == 0 else ("Short (1--5 yr)" if d <= 5 else
           ("Medium (6--15 yr)" if d <= 15 else "Long ($>$15 yr)"))


